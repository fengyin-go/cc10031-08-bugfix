# 脏数据隔离区 (DirtyDataVault)
# ---------------------------------------------------------------------------

@dataclass
class DirtyRecord:
    """脏数据记录：校验失败或解析异常的数据行。"""
    record_id: int
    source_module: str
    batch_ref: str
    raw_data: dict[str, Any]
    reason: str  # 如 "字段缺失", "格式非法", "解析超时"
    detected_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    quarantined: bool = True
    recovered_to: str | None = None


class DirtyDataVault:
    """脏数据隔离区：被校验规则或解析器标记为问题数据后移入此处。

    用法::

        vault = store.dirty_vault
        vault.quarantine("data_extract", "BATC-001", row, "缺少必填字段")
        dirty = vault.list_by_source("data_extract")
    """

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._seq = 0
        self._records: list[DirtyRecord] = []

    @property
    def count(self) -> int:
        with self._lock:
            return len(self._records)

    def quarantine(self, source: str, batch_ref: str,
                   raw_data: dict[str, Any], reason: str) -> DirtyRecord:
        with self._lock:
            self._seq += 1
            rec = DirtyRecord(
                record_id=self._seq, source_module=source,
                batch_ref=batch_ref, raw_data=raw_data, reason=reason,
            )
            self._records.append(rec)
            return rec

    def list_by_source(self, source: str) -> list[DirtyRecord]:
        with self._lock:
            return [r for r in self._records if r.source_module == source]

    def list_by_batch(self, batch_ref: str) -> list[DirtyRecord]:
        with self._lock:
            return [r for r in self._records if r.batch_ref == batch_ref]

    def mark_recovered(self, record_id: int, recovered_to: str) -> bool:
        with self._lock:
            for r in self._records:
                if r.record_id == record_id:
                    r.quarantined = False
                    r.recovered_to = recovered_to
                    return True
            return False

    def snapshot(self) -> dict[str, Any]:
        with self._lock:
            quarantined = sum(1 for r in self._records if r.quarantined)
            by_reason: dict[str, int] = {}
            for r in self._records:
                by_reason[r.reason] = by_reason.get(r.reason, 0) + 1
            return {
                "total": len(self._records),
                "quarantined": quarantined,
                "recovered": len(self._records) - quarantined,
                "by_reason": by_reason,
            }


# ---------------------------------------------------------------------------
# 采集记录 (CollectRecord) — 每次采集产出的结构化数据
# ---------------------------------------------------------------------------

@dataclass
class CollectEntry:
    entry_id: int
    batch_ref: str
    source_module: str
    fields: dict[str, Any]
    collected_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    validated: bool = False
    quality_score: float = 1.0


class CollectRecordStore:
    """采集记录存储：每次采集流程产出的结构化数据行。

    用法::

        rec = store.collect_records.add("BATC-001", "data_extract", {"字段1": "值1", ...})
        store.collect_records.mark_validated(rec.entry_id)
    """

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._seq = 0
        self._entries: list[CollectEntry] = []

    @property
    def count(self) -> int:
        with self._lock:
            return len(self._entries)

    def add(self, batch_ref: str, source: str,
            fields: dict[str, Any]) -> CollectEntry:
        with self._lock:
            self._seq += 1
            entry = CollectEntry(
                entry_id=self._seq, batch_ref=batch_ref,
                source_module=source, fields=dict(fields),
            )
            self._entries.append(entry)
            return entry

    def list_by_batch(self, batch_ref: str) -> list[CollectEntry]:
        with self._lock:
            return [e for e in self._entries if e.batch_ref == batch_ref]

    def list_by_source(self, source: str) -> list[CollectEntry]:
        with self._lock:
            return [e for e in self._entries if e.source_module == source]

    def mark_validated(self, entry_id: int, score: float = 1.0) -> bool:
        with self._lock:
            for e in self._entries:
                if e.entry_id == entry_id:
                    e.validated = True
                    e.quality_score = score
                    return True
            return False

    def snapshot(self) -> dict[str, Any]:
        with self._lock:
            validated = sum(1 for e in self._entries if e.validated)
            by_source: dict[str, int] = {}
            for e in self._entries:
                by_source[e.source_module] = by_source.get(e.source_module, 0) + 1
            return {
                "total": len(self._entries),
                "validated": validated,
                "unvalidated": len(self._entries) - validated,
                "by_source": by_source,
            }


# ---------------------------------------------------------------------------
# 规则版本档案 (RuleVersionArchive) — 站点上一已生效规则版本快照
# ---------------------------------------------------------------------------

class RuleVersionArchive:
    """保存每个站点最近一次「已生效」提取规则的版本快照。

    数据提取准入规则：只有「已生效」规则可以参与采集。当站点当前只剩
    草稿/已测试规则、但历史批次仍可读取时，允许回退到上一已生效版本
    继续采集；草稿规则在任何方案下都不会进入新的采集明细。

    用法::

        store.rule_archive.put("站点A", {"rule_id": 3, "rule_version": 2, ...})
        snapshots = store.rule_archive.all()
    """

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._items: dict[tuple[str, int], dict[str, Any]] = {}

    def put(self, site_key: str, snapshot: dict[str, Any]) -> None:
        """登记/覆盖某站点某规则的已生效版本快照。"""
        with self._lock:
            key = (site_key, int(snapshot.get("rule_id", 0)))
            self._items[key] = dict(snapshot)

    def all(self) -> list[dict[str, Any]]:
        with self._lock:
            return [dict(item) for item in self._items.values()]

    def remove_rule(self, site_key: str, rule_id: int) -> None:
        with self._lock:
            self._items.pop((site_key, int(rule_id)), None)

    @property
    def count(self) -> int:
        with self._lock:
            return len(self._items)

    def snapshot(self) -> dict[str, Any]:
        with self._lock:
            by_site: dict[str, int] = {}
            for (site_key, _), _item in self._items.items():
                by_site[site_key] = by_site.get(site_key, 0) + 1
            return {"total": len(self._items), "by_site": by_site}


# ---------------------------------------------------------------------------
# 字段映射采集明细台账 (FieldMappingLedger) — 每站点一份，版本号控制并发
# ---------------------------------------------------------------------------

class FieldMappingLedger:
    """字段映射采集明细台账：按站点持久保存最近一次采集的字段映射明细。

    每条明细记录每个字段实际命中的已生效规则版本，以及站点的准入状态、
    阻塞原因。写入采用乐观版本控制：

    - ``expected_version`` 与当前版本一致才接受写入（新站点传 0/None）；
    - 并发再次写入只接受一个版本，冲突方被拒绝，站点处理状态被推进
      终态 ``冲突终止``，需显式 ``reset_terminal`` 后才能继续写入。
    """

    #: 处理终态：并发写入冲突后站点源配置进入的终止状态
    CONFLICT_STATE = "冲突终止"
    PROCESS_STATES = ("待处理", "已准入", "已阻塞", CONFLICT_STATE)

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._records: dict[str, dict[str, Any]] = {}

    def get(self, site: str) -> dict[str, Any] | None:
        with self._lock:
            record = self._records.get(site)
            return dict(record) if record else None

    def list(self) -> list[dict[str, Any]]:
        with self._lock:
            return [dict(r) for r in self._records.values()]

    def upsert(
        self,
        site: str,
        detail: dict[str, Any],
        expected_version: int | None,
    ) -> tuple[str, dict[str, Any]]:
        """版本受控写入。返回 ("ok" | "conflict" | "terminated", record)。"""
        now = datetime.now(timezone.utc).isoformat()
        with self._lock:
            current = self._records.get(site)
            if current is not None and current.get("process_state") == self.CONFLICT_STATE:
                return "terminated", dict(current)
            if current is None:
                if expected_version not in (None, 0):
                    return "conflict", {}
                version = 1
            else:
                if expected_version != current.get("version"):
                    # 并发再次写入只接受一个版本：冲突方被拒绝，
                    # 站点源配置处理状态推进终态。
                    current["process_state"] = self.CONFLICT_STATE
                    current["updated_at"] = now
                    return "conflict", dict(current)
                version = int(current.get("version", 0)) + 1
            record = {
                **detail,
                "site": site,
                "version": version,
                "created_at": current.get("created_at") if current else now,
                "updated_at": now,
            }
            self._records[site] = record
            return "ok", dict(record)

    def reset_terminal(self, site: str) -> bool:
        """显式解除冲突终态（重新评估/重新发布源配置时调用）。"""
        with self._lock:
            current = self._records.get(site)
            if current is None or current.get("process_state") != self.CONFLICT_STATE:
                return False
            current["process_state"] = "待处理"
            current["updated_at"] = datetime.now(timezone.utc).isoformat()
            return True

    def snapshot(self) -> dict[str, Any]:
        with self._lock:
            by_state: dict[str, int] = {}
            for record in self._records.values():
                state = record.get("process_state", "待处理")
                by_state[state] = by_state.get(state, 0) + 1
            return {"total": len(self._records), "by_state": by_state}


